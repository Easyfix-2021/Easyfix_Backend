test('an EMPTY store falls back to env, and clears a previously primed key', async () => {
  const stored = newRecoveryKeypair();
  await resolveRecoveryPublicKey(store([{ public_key: stored.publicKey, active: true }]));
  try {
    assert.equal(parts(encryptField(ACCOUNT))[2], fpOfPublic(stored.publicKey));

    // The row is deleted. A stale cache would keep sealing to a key that is no
    // longer the active one and that nobody is looking after any more.
    const desc = await resolveRecoveryPublicKey(store([]));
    assert.equal(desc.source, 'env');
    assert.equal(parts(encryptField(ACCOUNT))[2], fpOfPublic(RECOVERY.publicKey));
  } finally {
    await resetRecoveryToEnv();
  }
});

test("NO store row and NO env resolves to source 'none' — the boot log must not cry wolf", async () => {
  /*
   * The descriptor is what server.js logs. It has to be able to say "no recovery
   * key is configured" as a STATEMENT OF FACT at info, because that is the
   * chosen configuration and a warning on every boot teaches everyone to ignore
   * warnings. A throw here would force the boot path to treat the normal state
   * as an error — which is exactly what it used to do.
   */
  await withRecoveryPublic(undefined, async () => {
    const desc = await resolveRecoveryPublicKey(store([]));
    assert.deepEqual(desc, { fingerprint: null, source: 'none' });
    // And writes carry on, unsealed.
    assert.equal(parts(encryptField(ACCOUNT))[2], NO_SEAL);
  });
  await resetRecoveryToEnv();
});

test('a CONFIGURED-but-broken store key still REJECTS — that is what keeps warn meaningful', async () => {
  // The other half of the boot-log split: source 'none' is info, a throw is
  // warn, and only a key someone actually configured can produce the throw.
  await withRecoveryPublic(undefined, async () => {
    await assert.rejects(() => resolveRecoveryPublicKey(store([{ public_key: 'not a key', active: true }])),
      (e) => e.code === 'FIELD_ENC_UNAVAILABLE');
  });
  await resetRecoveryToEnv();
});

test('a store row whose claimed fingerprint disagrees with its key is REFUSED', async () => {
  /*
   * The fingerprint is derived, but another writer owns that table and will put
   * a fingerprint column in it. The moment an id is STORED rather than computed,
   * it can disagree with the key it names — and every error message built on it
   * becomes a lie at the exact moment someone is trusting it. So it is checked,
   * not trusted.
   */
  const stored = newRecoveryKeypair();
  const rows = [{ fingerprint: 'deadbeef', public_key: stored.publicKey, active: true }];
  await assert.rejects(() => resolveRecoveryPublicKey(store(rows)), (e) => {
    assert.equal(e.code, 'FIELD_ENC_UNAVAILABLE');
    assert.ok(e.message.includes('deadbeef') && e.message.includes(fpOfPublic(stored.publicKey)));
    return true;
  });
  await resetRecoveryToEnv();
});

test('a store row with a weak or wrong-type key is REFUSED', async () => {
  for (const bad of [newRecoveryKeypair(1024).publicKey, 'not a key']) {
    // eslint-disable-next-line no-await-in-loop -- one store state per case.
    await assert.rejects(() => resolveRecoveryPublicKey(store([{ public_key: bad, active: true }])),
      (e) => e.code === 'FIELD_ENC_UNAVAILABLE');
  }
  await resetRecoveryToEnv();
});

test('recoveryKeyByFingerprint turns a rec_fp into something an operator recognises', async () => {
  const stored = newRecoveryKeypair();
  const fp = fpOfPublic(stored.publicKey);
  const rows = [{
    fingerprint: fp, public_key: stored.publicKey, active: false, label: 'notes-2026-03',
  }];
  const runner = store(rows);

  const found = await recoveryKeyByFingerprint(fp, runner);
  assert.equal(found.fp, fp);
  assert.equal(found.row.label, 'notes-2026-03', 'the store row comes back for display');
  assert.equal(await recoveryKeyByFingerprint('00000000', runner), null,
    'an unknown fingerprint is null, not a throw — "I do not know that key" is an answer');
  assert.equal(await recoveryKeyByFingerprint(fp, null), null, 'and no store is not a crash');
});

